def camel(name: str) -> str:
    """'text-on-primary' / 'Large Title' / 'space/16' -> camelCase identifier."""
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return out


def byte(x: float) -> int:
    return int((Decimal(str(x)) * 255).quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def hex6(rgb) -> str:
    return "#" + "".join(f"{byte(c):02X}" for c in rgb[:3])


def argb(rgba) -> str:
    """0xAARRGGBB with alpha = round(a * 255) half-up (AC-01b: 0.88 -> E0, 0.96 -> F5)."""
    return "0x" + f"{byte(rgba[3]):02X}" + "".join(f"{byte(c):02X}" for c in rgba[:3])


def alpha3(a: float) -> str:
    return str(Decimal(str(a)).quantize(Decimal("0.001"), rounding=ROUND_HALF_UP))


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def canonical_from_export(export: dict) -> dict:
    """Normalise a raw Figma export into the canonical comparison form."""
    colors = {}
    for full, (dark, _da, light, _la, _sc) in export["colors"].items():
        name = full.split("/", 1)[1]
        colors[name] = {
            "dark": {"hex": hex6(dark), "alpha": alpha3(dark[3]), "argb": argb(dark)},
            "light": {"hex": hex6(light), "alpha": alpha3(light[3]), "argb": argb(light)},
        }
    dims = {k: int(v) for k, v in export["dims"].items()}
    text = {}
    for name, fam, style, size, lh, ls, case in export["ts"]:
        text[name] = {"family": fam, "weight": style, "size": size, "lineHeight": lh,
                      "letterSpacingPercent": ls, "uppercase": case == "UPPER"}
    return {"colors": colors, "dims": dims, "text": text}
